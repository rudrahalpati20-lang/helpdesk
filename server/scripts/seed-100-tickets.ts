async function seed() {
  console.log(`Starting to seed ${ticketsData.length} diverse real-life tickets...`);

  // Verify users exist
  const existingUsers = await prisma.user.findMany({ select: { id: true } });
  const validUserIds = new Set(existingUsers.map((u) => u.id));

  let createdCount = 0;
  const now = new Date();

  for (const item of ticketsData) {
    const createdAt = new Date(now.getTime() - item.daysAgo * 24 * 60 * 60 * 1000);
    // Add random minute variation so tickets on the same day don't have identical timestamps
    createdAt.setMinutes(Math.floor(Math.random() * 60));
    createdAt.setSeconds(Math.floor(Math.random() * 60));

    const assignedId = item.assignedToId && validUserIds.has(item.assignedToId)
      ? item.assignedToId
      : null;

    let resolvedAt = createdAt;
    if (item.status === "resolved" || item.status === "closed") {
      if (item.replies && item.replies.length > 0) {
        const lastHours = Math.max(...item.replies.map((r) => r.hoursAfter));
        resolvedAt = new Date(createdAt.getTime() + lastHours * 60 * 60 * 1000);
      } else {
        const defaultMinutes =
          assignedId === AGENT_AI
            ? 2 + Math.floor(Math.random() * 4)
            : 45 + Math.floor(Math.random() * 180);
        resolvedAt = new Date(createdAt.getTime() + defaultMinutes * 60 * 1000);
      }
    }

    const ticket = await prisma.ticket.create({
      data: {
        subject: item.subject,
        body: item.body,
        status: item.status,
        category: item.category,
        senderName: item.senderName,
        senderEmail: item.senderEmail,
        assignedToId: assignedId,
        createdAt,
        updatedAt: resolvedAt,
      },
    });

    // Add replies if any
    if (item.replies && item.replies.length > 0) {
      for (const reply of item.replies) {
        const replyDate = new Date(createdAt.getTime() + reply.hoursAfter * 60 * 60 * 1000);
        const replyUserId = reply.userId && validUserIds.has(reply.userId)
          ? reply.userId
          : null;

        await prisma.reply.create({
          data: {
            ticketId: ticket.id,
            body: reply.body,
            senderType: reply.senderType,
            userId: replyUserId,
            createdAt: replyDate,
          },
        });
      }
    }

    createdCount++;
  }

  const finalCount = await prisma.ticket.count();
  console.log(`✅ Successfully created ${createdCount} tickets! Total tickets in database: ${finalCount}`);
}

seed()
  .catch((err) => {
    console.error("❌ Error seeding tickets:", err);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
